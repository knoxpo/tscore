// Generates generated/parse_big.ts: ~50k LOC of small unique functions.
// Cold parse+compile benchmark input — body executes two trivial calls.
// ponytail: regenerated at run time by run_compare.sh, never committed.
import { writeFileSync } from "node:fs";

const out = process.argv[2];
// 100 groups x 125 funcs x ~4 lines ~= 50k LOC.
// Grouped because tscore's register allocator caps bindings per frame (~250);
// a flat list of 12500 top-level functions fails with "out of registers".
const GROUPS = 100, PER = 125;
let src = "// generated by gen_parse_input.mjs — do not edit\n";
for (let g = 0; g < GROUPS; g++) {
    src += `function g${g}() {\n`;
    for (let j = 0; j < PER; j++) {
        const i = g * PER + j;
        src += `    function f${i}(a, b) {\n`;
        src += `        const c = a * ${(i % 97) + 1} + b - ${i % 13};\n`;
        src += `        if (c % 3 === 0) { return c - ${i % 7}; }\n`;
        src += `        return c + ${i % 11};\n    }\n`;
    }
    src += `    return f${g * PER}(1, 2) + f${g * PER + PER - 1}(3, 4);\n}\n`;
}
src += `console.log(\`RESULT \${g0() + g${GROUPS - 1}()}\`);\n`;
writeFileSync(out, src);
console.log(`wrote ${out}: ${GROUPS * PER} functions, ${src.split("\n").length} lines`);
